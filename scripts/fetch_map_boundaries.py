"""Bundle the two pilot state/district boundaries; no runtime tile service needed."""
import json
import unicodedata
from pathlib import Path
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parents[1]
PILOTS = {"chamoli": ("Uttarakhand", "Chamoli"), "kendrapara": ("Odisha", "Kendrapara")}


def get(url):
    with urlopen(Request(url, headers={"User-Agent": "Punarvaas-map-context/1.0"}), timeout=120) as response:
        return json.load(response)


def round_coordinates(value):
    return [round_coordinates(v) for v in value] if isinstance(value, list) else round(value, 5)


def main():
    sources, features = {}, {}
    for level in ("ADM1", "ADM2"):
        meta = get(f"https://www.geoboundaries.org/api/current/gbOpen/IND/{level}/")
        url = meta["simplifiedGeometryGeoJSON"]
        data = get(url)
        features[level] = {unicodedata.normalize("NFKD", f["properties"]["shapeName"]).encode("ascii", "ignore").decode().lower(): f for f in data["features"]}
        sources[level] = {k: meta[k] for k in ("boundaryID", "boundaryYearRepresented", "boundarySource",
                                             "boundaryLicense", "licenseSource", "simplifiedGeometryGeoJSON")}
    contexts = {}
    for code, (state, district) in PILOTS.items():
        # Some releases retain the former spelling Orissa.
        state_feature = features["ADM1"].get(state.lower()) or features["ADM1"].get("orissa" if state == "Odisha" else "uttaranchal")
        if not state_feature:
            raise ValueError(f"State not found: {state}; available: {list(features['ADM1'])}")
        contexts[code] = {"stateName": state, "districtName": district,
                          "state": state_feature, "district": features["ADM2"][district.lower()]}
        for kind in ("state", "district"):
            geometry = contexts[code][kind]["geometry"]
            geometry["coordinates"] = round_coordinates(geometry["coordinates"])
    target = ROOT / "web/src/map/state-boundaries.js"
    target.write_text("// Generated by scripts/fetch_map_boundaries.py. Attribution: docs/MAP_BOUNDARIES.md\n"
                      + "export const STATE_CONTEXTS = " + json.dumps(contexts, separators=(",", ":")) + ";\n", encoding="utf-8")
    (ROOT / "web/src/map/boundary-sources.json").write_text(json.dumps(sources, indent=2) + "\n", encoding="utf-8")
    print(f"Saved {len(contexts)} state/district contexts ({target.stat().st_size:,} bytes)")
    print(json.dumps(sources, indent=2))


if __name__ == "__main__":
    main()
