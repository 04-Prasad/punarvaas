"""
PUNARVAAS · landslide susceptibility.

Supervised, not heuristic. Training labels come from the GSI landslide
inventory (Bhukosh NLSM) where available; absences are sampled from terrain that
is plausibly stable, avoiding a 1 km buffer around known slides so the negative
class is not contaminated by unmapped failures.

Predictors are the standard, defensible set from the landslide-susceptibility
literature (Reichenbach et al. 2018 review): slope, curvature, wetness,
relief, distance to stream, elevation, aspect decomposed into northness/
eastness, extreme rainfall, and seismic loading.
"""
from __future__ import annotations

import numpy as np

from core.ml import Susceptibility, fit_susceptibility

FEATURES = ["slope_deg", "curvature", "twi", "relief_m", "distance_to_stream_m",
            "elevation_m", "northness", "eastness", "rain_1d_100yr_mm", "pga_g"]


def build_features(df) -> np.ndarray:
    a = np.radians(df["aspect_deg"].to_numpy(float))
    cols = {
        "slope_deg": df["slope_deg"].to_numpy(float),
        "curvature": df["curvature"].to_numpy(float),
        "twi": df["twi"].to_numpy(float),
        "relief_m": df["relief_m"].to_numpy(float),
        "distance_to_stream_m": df["distance_to_stream_m"].to_numpy(float),
        "elevation_m": df["elevation_m"].to_numpy(float),
        "northness": np.cos(a),
        "eastness": np.sin(a),
        "rain_1d_100yr_mm": df["rain_1d_100yr_mm"].to_numpy(float),
        "pga_g": df["pga_g"].to_numpy(float),
    }
    return np.column_stack([cols[f] for f in FEATURES])


def synthetic_inventory(df, n_pos: int = 900, seed: int = 5,
                        noise_frac: float = 0.55) -> np.ndarray:
    """Stand-in for the GSI inventory.

    Three properties make this a fair stand-in rather than a self-fulfilling one:

    1. Labels are generated by a *different* functional form than the model that
       will be fitted — hard thresholds, an interaction term, and spatially
       correlated mapping bias. If we generated labels with a logistic function
       of the same predictors, the reported AUC would be self-confirmation.
    2. Labels are Bernoulli-sampled from a probability, not taken as the top-k of
       a score. A deterministic top-k cut makes the label a pure function of the
       features and drives AUC to ~1.0, which is exactly the fake accuracy that
       discredits so much of the susceptibility literature. Real inventories are
       noisy: slopes fail without warning and mapped slides get missed.
    3. The nuisance and noise terms are scaled to a fixed fraction of the
       *signal's own* standard deviation (`noise_frac`), not to hard-coded
       constants. Hard constants mean the achievable AUC silently tracks whatever
       the terrain generator happens to produce — change the DEM and the
       "accuracy" moves for reasons that have nothing to do with the model.
       Pinning the signal-to-noise ratio makes the ceiling explicit: roughly
       0.85, which is what a well-fitted model on a good real inventory reaches.
    """
    rng = np.random.default_rng(seed)
    s = df["slope_deg"].to_numpy(float)
    cv = df["curvature"].to_numpy(float)
    tw = df["twi"].to_numpy(float)
    ds = df["distance_to_stream_m"].to_numpy(float)
    rel = df["relief_m"].to_numpy(float)

    # Toe undercutting is a proximity effect, so its scale must follow the
    # channel spacing of the landscape rather than a fixed 250 m: on a widely
    # spaced network a constant scale kills the predictor entirely.
    toe_scale = float(np.clip(np.median(ds) * 0.25, 80.0, 600.0))
    signal = (np.clip((s - 22.0) / 18.0, 0, 1.6) ** 1.4                 # threshold effect
              + 0.55 * np.clip(cv, 0, None) / (np.nanstd(cv) + 1e-9)     # concave hollows
              + 0.30 * np.clip((tw - 6.0) / 5.0, 0, 1.5)
              + 0.45 * np.exp(-ds / toe_scale)                           # toe undercutting
              + 0.25 * np.clip(rel / 400.0, 0, 1.5)
              + 0.60 * np.clip((s - 30.0) / 15.0, 0, 1) * np.clip(cv, 0, None))  # interaction
    sig_sd = float(np.std(signal)) + 1e-9

    # spatially correlated nuisance: real inventories are mapping-effort biased
    lat = df["lat"].to_numpy(float); lon = df["lon"].to_numpy(float)
    bias = np.sin(lat * 260.0) * np.cos(lon * 210.0)
    score = (signal
             + noise_frac * sig_sd * bias / (np.std(bias) + 1e-9)
             + noise_frac * sig_sd * rng.normal(0, 1.0, size=len(s)))

    # Convert to a probability calibrated to yield ≈ n_pos presences, then sample.
    target = min(n_pos, len(s) // 6)
    k = 2.2 / (np.std(score) + 1e-9)
    thr = np.quantile(score, 1.0 - target / len(s))
    p = 1.0 / (1.0 + np.exp(-k * (score - thr)))
    p *= target / max(p.sum(), 1e-9)
    return (rng.uniform(size=len(s)) < np.clip(p, 0, 1)).astype(int)


def sample_absences(y_pos: np.ndarray, df, ratio: float = 1.5, seed: int = 6,
                    buffer_m: float = 300.0) -> np.ndarray:
    """Boolean mask of rows to use as the negative class.

    Excludes cells within `buffer_m` of any inventory point: a cell one or two
    cells from a mapped slide is very likely unstable but simply unmapped, and
    labelling it 'stable' teaches the model the wrong boundary.

    The buffer is deliberately small (≈2 cell widths). A large buffer over-
    separates the classes — the model then only ever sees obviously-stable
    terrain as negatives, AUC inflates towards 1.0, and the reported skill
    becomes meaningless. Getting this wrong is the single most common way
    landslide-susceptibility papers report fake accuracy.
    """
    from core.grid.hexgrid import haversine_m
    rng = np.random.default_rng(seed)
    lat = df["lat"].to_numpy(float); lon = df["lon"].to_numpy(float)
    pi = np.flatnonzero(y_pos == 1)
    if pi.size == 0:
        return np.zeros(len(df), bool)
    dmin = np.full(len(df), np.inf)
    for i in pi:
        dmin = np.minimum(dmin, haversine_m(lat, lon, lat[i], lon[i]))
    eligible = np.flatnonzero((y_pos == 0) & (dmin > buffer_m))
    if eligible.size < 50:                      # buffer too aggressive; relax it
        eligible = np.flatnonzero((y_pos == 0) & (dmin > buffer_m / 2))
    n = min(int(ratio * pi.size), eligible.size)
    keep = rng.choice(eligible, n, replace=False) if n else np.array([], int)
    m = np.zeros(len(df), bool)
    m[keep] = True
    return m


def fit(df, inventory: np.ndarray | None = None, seed: int = 5):
    """Returns (susceptibility_0_1, model).

    The returned susceptibility is an *absolute* probability that the cell is a
    landslide source area, not a case–control ranking: the intercept is
    prior-corrected to the landscape prevalence before prediction. Downstream,
    `multi_hazard_union` multiplies this by an annual event rate, so a ranking
    passed off as a probability would inflate every rupee figure in the district.
    """
    y = synthetic_inventory(df, seed=seed) if inventory is None else np.asarray(inventory)
    neg = sample_absences(y, df, seed=seed + 1)
    train = (y == 1) | neg
    X = build_features(df)
    prev = float(y.sum()) / max(len(y), 1)
    model = fit_susceptibility(X[train], y[train], FEATURES, l2=1.0, seed=seed,
                               true_prevalence=prev)
    return np.clip(model.predict(X), 0.0, 1.0), model
